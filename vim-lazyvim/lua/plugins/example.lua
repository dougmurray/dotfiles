-- every spec file under the "plugins" directory will be loaded automatically by lazy.nvim
--
-- In your plugin files, you can:
-- * add extra plugins
-- * disable/enabled LazyVim plugins
-- * override the configuration of LazyVim plugins
return {
  -- disable noise.nvim, experimental UI box
  {
    "folke/noice.nvim",
    enabled = false
  },

  -- add gruvbox
  { "ellisonleao/gruvbox.nvim" },

  -- Configure LazyVim to load gruvbox
  {
    "LazyVim/LazyVim",
    opts = {
      colorscheme = "gruvbox",
    },
  },

  -- change trouble config
  {
    "folke/trouble.nvim",
    -- opts will be merged with the parent spec
    opts = { use_diagnostic_signs = true },
  },

  -- disable trouble
  { "folke/trouble.nvim", enabled = false },

  -- Note: current LazyVim defaults to blink.cmp (not nvim-cmp) and the Snacks
  -- picker (not telescope.nvim), so the old nvim-cmp/telescope.nvim override
  -- examples that used to live here were removed rather than installing
  -- unused plugins. See lazyvim.plugins.extras.coding.nvim-cmp / editor.telescope
  -- if you want to switch back to either of those.

  -- add pyright to lspconfig
  {
    "neovim/nvim-lspconfig",
    ---@class PluginLspOpts
    opts = {
      ---@type lspconfig.options
      servers = {
        -- pyright will be automatically installed with mason and loaded with lspconfig
        pyright = {},
      },
    },
  },

  -- LazyVim includes extra specs to properly setup lspconfig, treesitter,
  -- mason and typescript tooling for you (jose-elias-alvarez/typescript.nvim
  -- is unmaintained/deleted, so don't depend on it directly). Enabled via the
  -- "extras" list in lazyvim.json instead of importing it here, so the
  -- lazy.nvim import order check passes (see the ui.mini-starter note below).

  -- add more treesitter parsers
  {
    "nvim-treesitter/nvim-treesitter",
    opts = {
      ensure_installed = {
        "bash",
        "html",
        "javascript",
        "json",
        "lua",
        "markdown",
        "markdown_inline",
        "python",
        "query",
        "regex",
        "tsx",
        "typescript",
        "vim",
        "yaml",
      },
    },
  },

  -- since `vim.tbl_deep_extend`, can only merge tables and not lists, the code above
  -- would overwrite `ensure_installed` with the new value.
  -- If you'd rather extend the default config, use the code below instead:
  {
    "nvim-treesitter/nvim-treesitter",
    opts = function(_, opts)
      -- add tsx and treesitter
      vim.list_extend(opts.ensure_installed, {
        "tsx",
        "typescript",
      })
    end,
  },

  -- the opts function can also be used to change the default opts:
  {
    "nvim-lualine/lualine.nvim",
    event = "VeryLazy",
    opts = function(_, opts)
      table.insert(opts.sections.lualine_x, {
        function()
          return "😄"
        end,
      })
    end,
  },

  -- or you can return new options to override all the defaults
  {
    "nvim-lualine/lualine.nvim",
    event = "VeryLazy",
    opts = function()
      return {
        --[[add your custom lualine config here]]
      }
    end,
  },

  -- mini.starter is enabled via the "extras" list in lazyvim.json instead of
  -- importing it here directly, so it merges in the order LazyVim expects
  -- (importing it from a user plugin file causes a "dst: expected table, got
  -- nil" crash because it collides with the default snacks_picker extra).

  -- jsonls/schemastore/json treesitter: also enabled via lazyvim.json's
  -- "extras" list (see above) rather than imported here.

  -- add any tools you want to have installed below
  {
    "mason-org/mason.nvim",
    opts = {
      ensure_installed = {
        "stylua",
        "shellcheck",
        "shfmt",
        "flake8",
      },
    },
  },
}
